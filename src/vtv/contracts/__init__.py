"""Voice-to-Video contracts.

Every transformation in the pipeline has a schema, and every schema lives here
(Rule 9). This package is the shared language of the system: services, workers,
the API and eventually the TypeScript frontend all speak it, the last of those
via the JSON Schema files exported from :mod:`vtv.schema_export`.

The package has exactly two dependencies: the Python standard library and
pydantic. It imports nothing from :mod:`vtv.ports`, nothing from any service, and
nothing from any vendor SDK — a rule enforced by
``tests/test_architecture_boundaries.py`` rather than by good intentions.

The pipeline, and the document each step produces::

    Recording      voice captured                     recording.py
        |
    Transcript     what was said, with timings        transcript.py
        |
    Understanding  what it meant                      semantics.py
        |
    SceneGraph     how it becomes a story             scene.py
        |
    VisualPlan     what each scene should look like   visual_plan.py
        |
    Asset          the media that realises it         asset.py
        |
    Timeline       everything, placed in time         timeline.py
        |
    RenderJob      the finished MP4                   render.py

``Project`` (project.py) ties the chain together and tracks its state.
"""

